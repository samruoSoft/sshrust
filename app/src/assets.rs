pub struct EmbeddedAssets;

impl AssetSource for EmbeddedAssets {
    fn load(&self, path: &str) -> Result<Option<Cow<'static, [u8]>>, anyhow::Error> {
        // svg 元素的 path 形如 "icons/server.svg"
        let Some(name) = path
            .strip_prefix("icons/")
            .and_then(|p| p.strip_suffix(".svg"))
        else {
            return Ok(None);
        };
        Ok(ICONS
            .iter()
            .find(|(n, _)| *n == name)
            .map(|(_, svg)| Cow::Borrowed(svg.as_bytes())))
    }

    fn list(&self, path: &str) -> Result<Vec<gpui::SharedString>, anyhow::Error> {
        if path.starts_with("icons/") {
            Ok(ICONS
                .iter()
                .map(|(n, _)| gpui::SharedString::from(format!("icons/{n}.svg")))
                .collect())
        } else {
            Ok(Vec::new())
        }
    }
}
